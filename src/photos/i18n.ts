export type PhotoMessageKey = keyof typeof strings
export type PhotoMessageParams = Record<string, string | number>

export function tp(language: Language, key: PhotoMessageKey, params?: PhotoMessageParams): string {
  const text = strings[key][language === 'bn' ? 1 : 0]
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

export function photoLocale(language: Language): string {
  return language === 'bn' ? 'bn-IN' : 'en-IN'
}
